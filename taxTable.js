/**
 * 과세 기본급 및 부양가족 수 기반 간이세액 테이블 조회 함수
 * @param {number} baseSalary - 과세 대상 기본급
 * @param {number} dependents - 공제대상 가족수 (본인 포함, 1~11)
 * @returns {number|null} 매핑된 세액 (테이블에 없으면 null 반환하여 산식 처리)
 */
function lookupNtsTaxTable(baseSalary, dependents = 1) {
  // 공제가족 인덱스 보정 (1인 -> index 0, 11인 이상 -> index 10)
  const familyIdx = Math.min(Math.max(dependents, 1), 11) - 1;

  // 테이블 내 구간 매칭 탐색
  const matchedRow = NTS_TAX_TABLE.find(row => baseSalary >= row.min && baseSalary < row.max);

  if (matchedRow && matchedRow.taxes[familyIdx] !== undefined) {
    return matchedRow.taxes[familyIdx];
  }

  // 테이블 매핑 범위 밖일 경우 null 반환
  return null;
}
